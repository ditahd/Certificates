"""
Thinness certificate for Sp(6) hypergeometric monodromy: case C-32.


    alpha = (0, 0, 0, 0, 1/6, 5/6)
    beta  = (1/4, 3/4, 1/12, 5/12, 7/12, 11/12)


Background
----------

Beukers and Heckman classify the hypergeometric monodromy groups
Gamma(alpha, beta) = <A, B> generated by the companion matrices of

    f(x) = prod_j (x - exp(2 pi i alpha_j))
         = (x - 1)^4 Phi_6(x)
         = x^6 - 5 x^5 + 11 x^4 - 14 x^3 + 11 x^2 - 5 x + 1

    g(x) = prod_k (x - exp(2 pi i beta_k))
         = Phi_4(x) Phi_12(x)
         = x^6 + 1.

Case C-32 was one of the three cases left open by

    [BDN-thin]  Bajpai, Dona, Nitsche.
                Thin monodromy in Sp(4) and Sp(6).
                J. Algebra 664 (2025), 348-361. arXiv:2112.12111v3.

The companion matrices used here are the low-degree-first companion matrices.
They preserve an integral alternating form Omega of determinant 64, so the
natural ambient arithmetic group is Sp_Omega(Z).


Criterion
---------

This script verifies an exact projective ping-pong certificate.  It is not an
arithmeticity witness of the C-47/C-55 kind.  Instead it proves that Gamma is
virtually free, hence infinite index in the ambient arithmetic symplectic
group.

The proof works after a rational change of basis P.  In the new basis,

    S = P^{-1} B P

is a signed cyclic shift with S^6 = -I, and

    T = P^{-1} (B A^{-1}) P

is the rank-one transvection

    T(y0,...,y5) = (y0 + 5 y1 + 11 y2 + 14 y3 + 11 y4 + 5 y5,
                    y1,...,y5).

There is also an involution E satisfying

    E^2 = I,    E S E = S^{-1},    E T E = T^{-1}.

The ping-pong domain is built from a rational polyhedral cone

    K = { y in R^6 : H y >= 0 },

where H is the 77 x 6 integer matrix below.  Let

    X^+ = P(K^o),       X^- = E X^+,       X = X^+ union X^-,
    Y   = union_{k=1}^5 S^k X

in real projective space.  The rows y0 +/- yi, i=1,...,5, are included in H,
so K^o lies in the projective dominance chamber |y0| > |yi|.  Since S is a
signed cyclic shift, X and Y are projectively disjoint.

It remains to verify the plus-side branch inclusions

    G_i K subset K,   i = 0,...,10,

for

    T^{-1},
    T^{-1}S,       T^{-1}S E,
    -T^{-1}S^2,   -T^{-1}S^2 E,
    T^{-1}S^3,     T^{-1}S^3 E,
    -T^{-1}S^4,   -T^{-1}S^4 E,
    T^{-1}S^5,     T^{-1}S^5 E.

The signs are projectively harmless.  They only keep all branch images in the
same affine cone chart.


What this script verifies
-------------------------

    (a) The original companion matrices A and B preserve the displayed
        non-degenerate integral alternating form Omega.

    (b) The rational u-basis has determinant -64 and puts B, T = B A^{-1},
        and E into the claimed normal forms.

    (c) The cone K has no lineality, has non-empty interior, and its interior
        lies in the dominance chamber.

    (d) All eleven branch maps carry K into K.  This is checked exactly by
        converting the H-representation of K to exact extremal rays using
        cdd.gmp, then testing H G_i r >= 0 for every extremal ray r.

    (e) The conjugates S^i (T - I) S^{-i} generate the full Lie algebra
        sp_Q over Q.  This gives an exact Zariski-density check.

The final mathematical conclusion is that the projective group is

    <Tbar, Sbar> ~= Z * C_6,

and the original linear group is the central -I amalgam

    (Z x C_2) *_C_2 C_12.

This group has the Haagerup property.  Since any finite-index subgroup of the
ambient Sp(6)-arithmetic lattice has Kazhdan property (T), Gamma is infinite
index.  Together with (e), this proves that C-32 is thin.


Dependencies
------------

The C-47/C-55 witness scripts need only the Python standard library.  This
script additionally needs cdd.gmp for exact rational polyhedral conversion.
No floating-point arithmetic is used.
"""

