def companion(coeffs):
    """Companion matrix of a monic polynomial given coeffs low-to-high."""
    n = len(coeffs) - 1
    M = [[0] * n for _ in range(n)]
    for i in range(1, n):
        M[i][i - 1] = 1
    for i in range(n):
        M[i][-1] = -coeffs[i]
    return M


def eye(n):
    return [[1 if i == j else 0 for j in range(n)] for i in range(n)]


def zero(n, m):
    return [[0 for _ in range(m)] for _ in range(n)]


def mm(X, Y):
    n, k = len(X), len(Y)
    m = len(Y[0])
    return [
        [sum(X[i][p] * Y[p][j] for p in range(k)) for j in range(m)]
        for i in range(n)
    ]


def mv(M, v):
    return [sum(M[i][j] * v[j] for j in range(len(v))) for i in range(len(M))]


def msub(X, Y):
    return [[X[i][j] - Y[i][j] for j in range(len(X[0]))] for i in range(len(X))]


def madd(X, Y):
    return [[X[i][j] + Y[i][j] for j in range(len(X[0]))] for i in range(len(X))]


def mneg(X):
    return [[-x for x in row] for row in X]


def transpose(M):
    return [[M[j][i] for j in range(len(M))] for i in range(len(M[0]))]


def equal(X, Y):
    return all(
        X[i][j] == Y[i][j]
        for i in range(len(X))
        for j in range(len(X[0]))
    )


def inv_matrix(M, integral=False):
    """Inverse of an invertible matrix over Q; optionally assert integrality."""
    n = len(M)
    aug = [
        [Fraction(M[i][j]) for j in range(n)]
        + [Fraction(1 if i == j else 0) for j in range(n)]
        for i in range(n)
    ]
    for c in range(n):
        p = next((r for r in range(c, n) if aug[r][c] != 0), None)
        if p is None:
            raise AssertionError("matrix is singular")
        aug[c], aug[p] = aug[p], aug[c]
        f = aug[c][c]
        aug[c] = [x / f for x in aug[c]]
        for r in range(n):
            if r != c and aug[r][c] != 0:
                f = aug[r][c]
                aug[r] = [x - f * y for x, y in zip(aug[r], aug[c])]
    out = []
    for i in range(n):
        row = []
        for j in range(n):
            x = aug[i][n + j]
            if integral:
                assert x.denominator == 1, "non-integral inverse"
                x = int(x)
            row.append(x)
        out.append(row)
    return out


def to_int_matrix(M, label):
    out = []
    for row in M:
        out_row = []
        for x in row:
            x = Fraction(x)
            assert x.denominator == 1, f"{label} has non-integral entry {x}"
            out_row.append(int(x))
        out.append(out_row)
    return out


def mpow(M, exponent):
    if exponent < 0:
        return mpow(inv_matrix(M), -exponent)
    result = eye(len(M))
    base = M
    e = exponent
    while e:
        if e & 1:
            result = mm(base, result)
        base = mm(base, base)
        e >>= 1
    return result


def det_via_elim(M):
    """Determinant via exact elimination; works for integer or Fraction input."""
    n = len(M)
    M = [[Fraction(x) for x in row] for row in M]
    sign = Fraction(1)
    for c in range(n):
        p = next((i for i in range(c, n) if M[i][c] != 0), None)
        if p is None:
            return Fraction(0)
        if p != c:
            M[c], M[p] = M[p], M[c]
            sign = -sign
        for i in range(c + 1, n):
            f = M[i][c] / M[c][c]
            M[i] = [M[i][j] - f * M[c][j] for j in range(n)]
    d = sign
    for i in range(n):
        d *= M[i][i]
    return d


def row_dot(row, vector):
    return sum(row[i] * vector[i] for i in range(len(vector)))


def rank_rows(rows):
    R = [[Fraction(x) for x in row] for row in rows if any(x != 0 for x in row)]
    if not R:
        return 0
    nrows = len(R)
    ncols = len(R[0])
    r = 0
    for c in range(ncols):
        if r >= nrows:
            break
        p = next((i for i in range(r, nrows) if R[i][c] != 0), None)
        if p is None:
            continue
        R[r], R[p] = R[p], R[r]
        f = R[r][c]
        R[r] = [x / f for x in R[r]]
        for i in range(nrows):
            if i != r and R[i][c] != 0:
                f = R[i][c]
                R[i] = [x - f * y for x, y in zip(R[i], R[r])]
        r += 1
    return r


def flatten(M):
    return [x for row in M for x in row]


def rank_matrices(mats):
    return rank_rows([flatten(M) for M in mats])


def cdd_extreme_rays_from_H(H):
    """Exact extremal rays of K = {y : H y >= 0}."""
    inequalities = [[Fraction(0)] + [Fraction(x) for x in row] for row in H]
    mat = cdd.matrix_from_array(inequalities, rep_type=cdd.RepType.INEQUALITY)
    poly = cdd.polyhedron_from_matrix(mat)
    generators = cdd.copy_generators(poly)
    rays = []
    lines = []
    lin_set = set(generators.lin_set)
    for idx, row in enumerate(generators.array):
        vector = tuple(Fraction(x) for x in row[1:])
        if idx in lin_set:
            lines.append(vector)
        elif any(vector):
            rays.append(vector)
    return rays, lines


def min_H_on_vectors(H, vectors):
    return min(row_dot(row, vector) for row in H for vector in vectors)


