def branch_maps():
    out = [("T^-1", T_INV)]
    for k in range(1, 6):
        eps = 1 if k % 2 == 1 else -1
        base = mm(T_INV, mpow(S, k))
        if eps == -1:
            base = mneg(base)
        out.append((f"{'-' if eps == -1 else ''}T^-1 S^{k}", base))

        with_e = mm(mm(T_INV, mpow(S, k)), E)
        if eps == -1:
            with_e = mneg(with_e)
        out.append((f"{'-' if eps == -1 else ''}T^-1 S^{k} E", with_e))
    return out


def verify_branch_inclusions(rays):
    minima = {}
    for name, G in branch_maps():
        min_value = None
        for ray_index, ray in enumerate(rays):
            image = mv(G, ray)
            for row_index, row in enumerate(H):
                value = row_dot(row, image)
                min_value = value if min_value is None else min(min_value, value)
                assert value >= 0, (
                    f"{name}K subset K failed on ray {ray_index}, "
                    f"facet {row_index}, value {value}"
                )
        minima[name] = min_value
    return minima


def lie_algebra_dimension():
    """Lie algebra generated by S^i (T-I) S^{-i}, checked over Q."""
    basis = []

    def add_to_basis(M):
        r0 = rank_matrices(basis)
        r1 = rank_matrices(basis + [M])
        if r1 > r0:
            basis.append(M)
            return True
        return False

    N = msub(T, I6)
    S_inv = inv_matrix(S, integral=True)
    for i in range(6):
        add_to_basis(mm(mm(mpow(S, i), N), mpow(S_inv, i)))

    changed = True
    while changed:
        changed = False
        current = list(basis)
        for X in current:
            for Y in current:
                if add_to_basis(msub(mm(X, Y), mm(Y, X))):
                    changed = True

    return basis


